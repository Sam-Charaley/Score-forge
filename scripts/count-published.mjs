// Regenerates src/data/publishedCounts.js: how many reviewed questions and
// FRQs each subject has. Run it after changing any reviewed flag:
//   npm run counts
// publishedCounts.test.js fails if the file and the content disagree.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { bankSubjects, frqSubjects, loadQuestions, loadFrqSet } from './lib/content.mjs';

const OUTPUT_FILE = path.resolve('src/data/publishedCounts.js');

async function main() {
  // A subject that shares a folder (Calc AB draws on ../calc/) is still
  // counted on its own, so each count is what that subject's students see.
  const subjects = [...new Set([...bankSubjects(), ...frqSubjects()])].sort();
  const counts = {};
  for (const subjectId of subjects) {
    const [questions, { frqs }] = await Promise.all([loadQuestions(subjectId), loadFrqSet(subjectId)]);
    counts[subjectId] = {
      questions: questions.filter(q => q.reviewed === true).length,
      frqs: frqs.filter(f => f.reviewed === true).length,
    };
  }
  const lines = subjects.map(id => `  ${id}: { questions: ${counts[id].questions}, frqs: ${counts[id].frqs} },`);
  writeFileSync(OUTPUT_FILE, `// Reviewed (published) questions and FRQs per subject, so the app can tell
// which subjects have anything to practice without downloading every bank.
// Generated by \`npm run counts\`; publishedCounts.test.js fails if it drifts.
export const PUBLISHED_COUNTS = {
${lines.join('\n')}
};
`);
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT_FILE)}:`);
  subjects.forEach(id => console.log(`  ${id.padEnd(8)} ${String(counts[id].questions).padStart(4)} questions, ${counts[id].frqs} FRQs`));
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
